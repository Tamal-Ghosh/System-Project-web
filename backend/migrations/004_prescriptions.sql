CREATE TABLE IF NOT EXISTS public.prescriptions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    assessment_id uuid NOT NULL UNIQUE REFERENCES public.doctor_assessments(id) ON DELETE CASCADE,
    patient_id text NOT NULL CHECK (patient_id ~ '^[A-Za-z0-9][A-Za-z0-9_-]{2,39}$'),
    symptoms text[] NOT NULL DEFAULT '{}',
    allergy_status text NOT NULL CHECK (allergy_status IN ('none_known', 'present', 'unknown')),
    allergy_details text CHECK (allergy_details IS NULL OR char_length(allergy_details) <= 500),
    medications jsonb NOT NULL CHECK (jsonb_typeof(medications) = 'array' AND jsonb_array_length(medications) BETWEEN 1 AND 10),
    follow_up text CHECK (follow_up IS NULL OR char_length(follow_up) <= 500),
    prescriber_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    prescriber_name text CHECK (prescriber_name IS NULL OR char_length(prescriber_name) BETWEEN 2 AND 120),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (cardinality(symptoms) <= 12),
    CHECK (allergy_status <> 'present' OR allergy_details IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS prescriptions_patient_id_created_idx
    ON public.prescriptions (patient_id, created_at DESC);

ALTER TABLE public.prescriptions ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.prescriptions IS
    'Clinician-authored prescriptions linked to completed assessments. No medication is generated by the model.';
